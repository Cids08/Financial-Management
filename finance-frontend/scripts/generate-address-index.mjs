import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

/* ---------------------------------------------------------------------- */
/* Generates src/data/generatedAddressIndex.js from the vendored official   */
/* PSGC snapshot (psgc-data/psgc_2025-07-31.csv, Philippine Statistics      */
/* Authority). Run via:  npm run generate:addresses                         */
/*                                                                          */
/* The CSV rows are ordered parent-before-child, so the current province is */
/* tracked while scanning, and each city/municipality prints under the      */
/* province that precedes it. Independent/HUC cities (Baguio, Davao, ...)   */
/* and NCR roll straight up to their region. Output shape matches the       */
/* handcrafted GOOGLE_PLACES_INDEX entries so AddressSelector consumes it   */
/* identically. Nothing here is hand-maintained.                           */
/* ---------------------------------------------------------------------- */

const here = path.dirname(fileURLToPath(import.meta.url))
const csvPath = path.join(here, '..', 'psgc-data', 'psgc_2025-07-31.csv')

const lines = readFileSync(csvPath, 'utf8').trim().split('\n')
// headers: psgc_id,name,correspondence_code,geographic_level,...
const rows = lines.slice(1).map((l) => {
  const p = l.split(',')
  return { code: p[0], name: p[1].trim(), level: p[3] }
})

const LEVEL_CITY = new Set(['City', 'Mun', 'SubMun'])
const SHORT_REGION = (name) =>
  (name.match(/\(([^)]+)\)/) || [, name])[1].trim() || name

// A municipality belongs to its province when its 10-digit PSGC code shares
// the province's 5-digit prefix (e.g. Aklan "0600400000" -> "06004" covers
// Altavas "0600401000", Balete "0600402000", ...). Independent/HUC cities
// (Davao City, Baguio, Iloilo, ...) and all NCR cities match no province, so
// they fall back to their region label.
const provByPrefix = new Map()

const entries = []
const seen = new Set()
let regionName = ''
let regionCode = ''

const emit = (raw) => {
  const city = raw.name.replace(/^City of (.+)$/, '$1 City')
  let province = provByPrefix.get(raw.code.slice(0, 5))
  if (!province) {
    province = regionCode === '13' ? 'Metro Manila' : SHORT_REGION(regionName) || 'Philippines'
  }
  const description = `${city}, ${province}, Philippines`
  const key = description.toLowerCase()
  if (seen.has(key)) return
  seen.add(key)
  entries.push({
    description,
    address_components: {
      route: '',
      locality: city,
      administrative_area_level_1: province,
      country: 'Philippines',
      country_code: 'PH',
      postal_code: '',
    },
    isLocal: true,
  })
}

for (const r of rows) {
  if (r.level === 'Reg') {
    regionName = r.name
    regionCode = r.code.slice(0, 2)
  } else if (r.level === 'Prov') {
    provByPrefix.set(r.code.slice(0, 5), r.name)
  } else if (LEVEL_CITY.has(r.level)) {
    emit(r)
  }
}

entries.sort((a, b) => a.description.localeCompare(b.description))

const out = `// AUTO-GENERATED — do not edit by hand.
// Generated by scripts/generate-address-index.mjs from the official PSGC
// snapshot in psgc-data/ (Philippine Statistics Authority, public domain).
// Run \`npm run generate:addresses\` to rebuild after updating the snapshot.

export const GENERATED_PH_ADDRESS_INDEX = ${JSON.stringify(entries, null, 0)}
`

writeFileSync(path.join(here, '..', 'src', 'data', 'generatedAddressIndex.js'), out, 'utf8')
console.log(`generated ${entries.length} PSGC address entries -> src/data/generatedAddressIndex.js`)